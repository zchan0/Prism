import AppKit
import CryptoKit
import ImageIO

/// One representation of a copy: a pasteboard type and its bytes.
struct Representation: Codable, Equatable, Sendable {
    let type: String
    let data: Data
}

/// Everything kept of one copy: for each pasteboard item, the representations it had, in the order the app that
/// copied it declared them. Several files copied at once are several items.
typealias Payload = [[Representation]]

enum ClipTypes {
    /// The only representations kept. Others, such as an app's private formats, are dropped.
    static let kept: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .png, .tiff, .fileURL, .color]
    /// Markers from nspasteboard.org: a password, something that is on the clipboard only for a moment, or something
    /// the person did not copy themselves.
    static let skipped: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]
}

/// One copy in the history. The index stores it as JSON, so renaming a property loses the person's history.
struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    enum Kind: String, Codable, Sendable {
        case text, image, file, color
    }

    /// Text beyond this is left out of the index, so the index stays small enough to rewrite on every copy.
    static let searchableLength = 10_000

    let id: UUID
    let kind: Kind
    /// Two copies with the same digest have the same representations, byte for byte.
    let digest: String
    let byteCount: Int
    /// The plain text of text and colors, up to `searchableLength` characters.
    let text: String?
    let filePaths: [String]?
    /// The color as it was copied, such as `rgb(240, 81, 56)`, or `#RRGGBB` when only a color object was copied.
    let colorValue: String?
    /// sRGB red, green, blue and alpha, each from 0 to 1.
    let rgba: [Double]?
    let pixelWidth: Int?
    let pixelHeight: Int?
    /// When it was last copied, or picked from the history. An index saved before this was kept has none.
    var copiedAt: Date?

    var fileNames: [String] {
        (filePaths ?? []).map { ($0 as NSString).lastPathComponent }
    }

    /// Text that is a single web address.
    var isLink: Bool {
        guard kind == .text, let text = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              text.hasPrefix("http://") || text.hasPrefix("https://") else { return false }
        return !text.contains { $0.isWhitespace }
    }

    /// Case-insensitive, on the text, the file names or the color value. Images have no text to match.
    func matches(_ query: String) -> Bool {
        guard !query.isEmpty else { return true }
        let haystacks: [String]
        switch kind {
        case .text: haystacks = [text].compactMap { $0 }
        case .color: haystacks = [colorValue, text].compactMap { $0 }
        case .file: haystacks = fileNames
        case .image: haystacks = []
        }
        return haystacks.contains { $0.range(of: query, options: .caseInsensitive) != nil }
    }
}

extension ClipItem {
    /// Nil when the payload has nothing to show.
    init?(id: UUID, payload: Payload) {
        let representations = payload.flatMap { $0 }
        guard !representations.isEmpty else { return nil }
        let types = Set(representations.map(\.type))
        let plainText = Self.plainText(in: payload)
        let parsedColor = plainText.flatMap(ColorValue.parse)
        let kind = Self.kind(types: types, text: plainText)

        var colorValue: String?
        var rgba: [Double]?
        if kind == .color {
            if let parsedColor, let plainText {
                colorValue = plainText.trimmingCharacters(in: .whitespacesAndNewlines)
                rgba = parsedColor
            } else if let data = Self.first(.color, in: payload), let color = ColorValue.color(archivedIn: data) {
                colorValue = ColorValue.hex(color)
                rgba = color
            }
        }
        var pixelSize: (width: Int, height: Int)?
        if kind == .image, let data = Self.first(.png, in: payload) ?? Self.first(.tiff, in: payload) {
            pixelSize = Self.pixelSize(of: data)
        }

        self.init(
            id: id,
            kind: kind,
            digest: Self.digest(of: payload),
            byteCount: representations.reduce(0) { $0 + $1.data.count },
            text: kind == .text || kind == .color ? plainText.map { String($0.prefix(Self.searchableLength)) } : nil,
            filePaths: kind == .file ? Self.filePaths(in: payload) : nil,
            colorValue: colorValue,
            rgba: rgba,
            pixelWidth: pixelSize?.width,
            pixelHeight: pixelSize?.height
        )
    }

    static func kind(types: Set<String>, text: String?) -> Kind {
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) { return .file }
        if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            return .image
        }
        if types.contains(NSPasteboard.PasteboardType.color.rawValue) || text.flatMap(ColorValue.parse) != nil {
            return .color
        }
        return .text
    }

    static func digest(of payload: Payload) -> String {
        var hasher = SHA256()
        for (index, item) in payload.enumerated() {
            for representation in item {
                // The item index and the lengths keep two different payloads from running together into one stream.
                let header = "\(index)|\(representation.type)|\(representation.data.count)|"
                hasher.update(data: Data(header.utf8))
                hasher.update(data: representation.data)
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    private static func first(_ type: NSPasteboard.PasteboardType, in payload: Payload) -> Data? {
        payload.lazy.flatMap { $0 }.first { $0.type == type.rawValue }?.data
    }

    /// The plain text if the app wrote one, or else the text of its rich text or HTML.
    private static func plainText(in payload: Payload) -> String? {
        if let data = first(.string, in: payload) {
            return String(decoding: data, as: UTF8.self)
        }
        if let data = first(.rtf, in: payload) {
            return NSAttributedString(rtf: data, documentAttributes: nil)?.string
        }
        if let data = first(.html, in: payload) {
            // Not NSAttributedString's HTML import: it loads WebKit on the main thread.
            let html = String(decoding: data, as: UTF8.self)
            return html.replacingOccurrences(of: "<[^>]+>", with: "", options: .regularExpression)
                .trimmingCharacters(in: .whitespacesAndNewlines)
        }
        return nil
    }

    private static func filePaths(in payload: Payload) -> [String] {
        payload.flatMap { $0 }
            .filter { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }
            .compactMap { representation in
                guard let url = URL(dataRepresentation: representation.data, relativeTo: nil) else { return nil }
                // Finder copies file reference URLs, such as file:///.file/id=…, which have no name to show.
                return ((url as NSURL).filePathURL ?? url).path
            }
    }

    private static func pixelSize(of data: Data) -> (width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int else { return nil }
        return (width, height)
    }
}

/// Which kinds of items the history window lists.
enum ClipFilter: CaseIterable, Sendable {
    case all
    /// Text and colors; links are text too.
    case text
    case links
    case images
    case files

    func includes(_ item: ClipItem) -> Bool {
        switch self {
        case .all: true
        case .text: item.kind == .text || item.kind == .color
        case .links: item.isLink
        case .images: item.kind == .image
        case .files: item.kind == .file
        }
    }

    /// The next one in the menu's order, wrapping around; backwards when `offset` is negative.
    func cycled(by offset: Int) -> ClipFilter {
        let all = Self.allCases
        let index = all.firstIndex(of: self) ?? 0
        return all[((index + offset) % all.count + all.count) % all.count]
    }
}

/// Colors written as text: `#RGB`, `#RRGGBB`, `#RRGGBBAA`, `rgb(r, g, b)` and `rgba(r, g, b, a)`.
enum ColorValue {
    /// sRGB red, green, blue and alpha, each from 0 to 1, or nil when the whole text is not one color.
    static func parse(_ text: String) -> [Double]? {
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if value.hasPrefix("#") {
            return hex(String(value.dropFirst()))
        }
        for (prefix, count) in [("rgba(", 4), ("rgb(", 3)] where value.hasPrefix(prefix) && value.hasSuffix(")") {
            let parts = value.dropFirst(prefix.count).dropLast()
                .split(separator: ",", omittingEmptySubsequences: false)
                .map { $0.trimmingCharacters(in: .whitespaces) }
            guard parts.count == count else { return nil }
            var components: [Double] = []
            for part in parts.prefix(3) {
                guard let channel = Int(part), (0...255).contains(channel) else { return nil }
                components.append(Double(channel) / 255)
            }
            if count == 4 {
                guard let alpha = Double(parts[3]), (0...1).contains(alpha) else { return nil }
                components.append(alpha)
            } else {
                components.append(1)
            }
            return components
        }
        return nil
    }

    private static func hex(_ digits: String) -> [Double]? {
        guard [3, 6, 8].contains(digits.count), digits.allSatisfy(\.isHexDigit) else { return nil }
        let expanded = digits.count == 3 ? digits.map { "\($0)\($0)" }.joined() : digits
        guard let value = UInt64(expanded, radix: 16) else { return nil }
        let channels = expanded.count == 8
            ? [value >> 24, value >> 16, value >> 8, value]
            : [value >> 16, value >> 8, value]
        var components = channels.map { Double($0 & 0xFF) / 255 }
        if components.count == 3 { components.append(1) }
        return components
    }

    /// The sRGB components of a color an app copied as a color object, as the color panel does.
    static func color(archivedIn data: Data) -> [Double]? {
        guard let color = try? NSKeyedUnarchiver.unarchivedObject(ofClass: NSColor.self, from: data),
              let srgb = color.usingColorSpace(.sRGB) else { return nil }
        return [srgb.redComponent, srgb.greenComponent, srgb.blueComponent, srgb.alphaComponent].map(Double.init)
    }

    static func hex(_ rgba: [Double]) -> String {
        let bytes = rgba.map { Int(($0 * 255).rounded()).clamped(to: 0...255) }
        let shown = bytes.count == 4 && bytes[3] == 255 ? bytes.prefix(3) : bytes.prefix(4)
        return "#" + shown.map { String(format: "%02X", $0) }.joined()
    }
}

private extension Comparable {
    func clamped(to range: ClosedRange<Self>) -> Self {
        min(max(self, range.lowerBound), range.upperBound)
    }
}
